import re

def clean_text(text):
    """Basic NLP preprocessing: lowercase, remove URLs/special characters and extra spaces."""
    text = text.lower()
    text = re.sub(r"https?://\S+|www\.\S+", " ", text)
    text = re.sub(r"[^a-z0-9\s]", " ", text)
    text = re.sub(r"\s+", " ", text).strip()
    return text
